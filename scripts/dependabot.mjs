/**
 * .github/dependabot.yml, rendered for the tree it sits in (ticket #81).
 *
 * The file ships with the core into every shop, and Dependabot reads it
 * wherever it finds it. In the core repository that is the point: the bumps
 * arrive as pull requests, are reviewed, and leave in a core version. In a
 * shop the same pull requests edit package.json and package-lock.json, two
 * core files: merged, each is a core divergence nobody approved, back as a
 * conflict at the next `shopctl core upgrade`; ignored, they pile up in every
 * repository of the fleet (a demonstration shop got three on its first day).
 * A shop's dependencies move with its core version, and nothing else.
 *
 * Dependabot has no condition on the repository it runs in, so the file
 * itself differs: a shop's rendering sets `open-pull-requests-limit` to 0,
 * which is how Dependabot is told to open no version update at all. Rendered,
 * not hand-kept, for the reason CODEOWNERS is: check-paths.mjs holds the file
 * to this function in both trees, `shopctl new` and `shopctl core upgrade`
 * render the shop's, and the core-change gate takes a rendering for what it
 * is rather than for a shop editing a core file.
 *
 * Edit the core's Dependabot configuration HERE, then
 * `npm run check:paths -- --write`.
 */

export const DEPENDABOT_FILE = '.github/dependabot.yml';

const HEADER = '# GENERATED by scripts/check-paths.mjs from scripts/dependabot.mjs — do not edit.';

/** The core repository's: weekly bumps, grouped, as reviewed pull requests. */
const CORE = `${HEADER}
#
# Dependabot keeps the core's dependencies current with automated PRs. A shop
# (a tree with client/client.yaml) renders this file with version updates off:
# its dependencies are the core's and move with \`shopctl core upgrade\`.
version: 2
updates:
  - package-ecosystem: "npm"
    directory: "/"
    schedule:
      interval: "weekly"
    open-pull-requests-limit: 5
    groups:
      # Bundle minor + patch bumps into one PR per week to cut noise; majors
      # (e.g. the Astro 5→6 / Node 22 kind of jump) still come as their own PRs
      # so they get individual review.
      minor-and-patch:
        update-types:
          - "minor"
          - "patch"
    ignore:
      # TypeScript 7 ships the native (Go) compiler, which does not expose the
      # programmatic API \`astro check\` drives through @astrojs/language-server;
      # @astrojs/check also still peers on \`^5 || ^6\`, so \`npm ci\` cannot even
      # resolve. Track https://github.com/withastro/roadmap/discussions/1321 and
      # drop this entry once Astro supports the native compiler.
      - dependency-name: "typescript"
        versions: [">=7.0.0"]
`;

/** A shop's: no version update, ever. */
const SHOP = `${HEADER}
#
# A shop's dependencies are the core's: package.json and package-lock.json are
# core files, and they move with \`shopctl core upgrade\`. A Dependabot pull
# request here would be a core edit nobody approved, back as a conflict at the
# next upgrade, so version updates are off (open-pull-requests-limit: 0).
#
# Dependabot alerts still say when a dependency is vulnerable; the fix comes in
# a core version. Leave "Dependabot security updates" off in the repository's
# settings, for the same reason.
version: 2
updates:
  - package-ecosystem: "npm"
    directory: "/"
    schedule:
      interval: "weekly"
    open-pull-requests-limit: 0
`;

/**
 * @param {{ shop: boolean }} tree whether the tree is a shop (client/client.yaml)
 * @returns {string} the file's content
 */
export function renderDependabot({ shop }) {
  return shop ? SHOP : CORE;
}
