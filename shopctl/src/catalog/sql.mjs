/**
 * Turning an import operation into SQL, safely.
 *
 * The applier hands D1 a FILE of statements (`wrangler d1 execute --file`),
 * which is the only shape that keeps a two-hundred-product import to one round
 * trip instead of two thousand. The cost of that shape is that there are no
 * bound parameters: every value is inlined, and a product description is
 * arbitrary text a merchant pasted from somewhere.
 *
 * So `text()` is the whole security surface of this module, and it is written to
 * be boring: single quotes doubled, per the SQL standard, and anything that
 * cannot survive being inlined refused outright rather than escaped
 * imaginatively. A NUL byte terminates a string in more parsers than it should,
 * so it never reaches one from here. Nothing else needs escaping inside a SQLite
 * single-quoted literal — backslash is not an escape character there, which is
 * the mistake that makes MySQL-shaped escaping wrong.
 *
 * The catalogue's own validation is not the defence. It is a defence, and it
 * runs first, but a description is deliberately free text: the quoting has to
 * hold on its own for a name that is literally `'); DROP TABLE products;--`,
 * which is what test/scripts/catalog.test.mjs writes into the store and reads
 * back verbatim.
 */

/** A SQL string literal, or a refusal. */
export function text(value) {
  const string = String(value);
  if (string.includes('\0')) {
    throw new Error('a catalogue value contains a NUL byte, which cannot be written as a SQL literal.');
  }
  return `'${string.replaceAll("'", "''")}'`;
}

/** A nullable string literal. */
export function textOrNull(value) {
  return value == null || value === '' ? 'NULL' : text(value);
}

/** An integer literal, or a refusal. Never a float, never a string that happens
 *  to look numeric: `stock = '3'` compares differently from `stock = 3`. */
export function integer(value) {
  if (!Number.isSafeInteger(value)) {
    throw new Error(`expected a whole number for a SQL literal, got ${JSON.stringify(value)}.`);
  }
  return String(value);
}

export function integerOrNull(value) {
  return value == null ? 'NULL' : integer(value);
}

/**
 * A fresh public identifier, generated by SQLite rather than by this process.
 *
 * The same expression migration 0033's backfill and `seed-demo.sql` use. Hex
 * digits are a subset of the Crockford base32 alphabet public IDs are validated
 * against (`parsePublicId` in features/ids/publicId.ts) — no i, l, o or u
 * appears in `0-9a-f` — so an id minted here is indistinguishable from one the
 * application minted, and this file needs no third copy of that alphabet.
 */
export function newPublicId(prefix) {
  return `'${prefix}_' || lower(substr(hex(randomblob(10)), 1, 10))`;
}

/** The id of a product this import addresses by its reference. */
export function productIdBySku(sku) {
  return `(SELECT id FROM products WHERE sku = ${text(sku)})`;
}
